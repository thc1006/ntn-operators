// configTemplate generates OCUDU-compatible NTN configuration YAML.
//
// This format was validated against OCUDU gNB (migrated from srsRAN_Project).
// Key format differences from the old docs-era geo_ntn.yml:
//   - ta_common is under ntn.ta_info (not ntn.ta_common)
//   - ephemeris uses ephemeris_info_ecef or ephemeris_orbital (variant)
//   - sib_mapping is scalar 19 (not array [19])
//   - si_window_position is REQUIRED for SIB19
//   - pucch.sr_period_ms is omitted (let gNB use bandwidth-appropriate default)
const configTemplate = `# Generated by NTN K8s Operators — do not edit manually
# Payload type: {{ .PayloadType }} (3GPP Rel-19: transparent or regenerative)

ntn:
  cell_specific_koffset: {{ .Koffset }}
  ta_info:
    ta_common: {{ .TACommon }}
{{- if .TAInfoExtended }}
    ta_common_drift: {{ .TACommonDrift }}
    ta_common_drift_variant: {{ .TACommonDriftVariant }}
    ta_common_offset: {{ .TACommonOffset }}
{{- end }}
{{- if .UseOrbital }}
  ephemeris_orbital:
    semi_major_axis: {{ .OrbSemiMajorAxis }}
    eccentricity: {{ .OrbEccentricity }}
    inclination: {{ .OrbInclination }}
    right_ascension: {{ .OrbRightAscension }}
    arg_of_periapsis: {{ .OrbArgOfPeriapsis }}
    mean_anomaly: {{ .OrbMeanAnomaly }}
{{- else }}
  ephemeris_info_ecef:
    pos_x: {{ .EphPosX }}
    pos_y: {{ .EphPosY }}
    pos_z: {{ .EphPosZ }}
    vel_x: {{ .EphVelX }}
    vel_y: {{ .EphVelY }}
    vel_z: {{ .EphVelZ }}
{{- end }}
{{- if .EpochTime }}
  epoch_time:
    sfn: {{ .EpochSFN }}
    subframe_number: {{ .EpochSubframeNumber }}
{{- end }}
{{- if .FeederLink }}
  feeder_link_info:
    enable_doppler_compensation: {{ .FeederDopplerCompensation }}
    dl_freq: {{ .FeederDLFreq }}
    ul_freq: {{ .FeederULFreq }}
{{- end }}
{{- if .GatewayLocation }}
  ntn_gateway_location:
    latitude: {{ .GatewayLatitude }}
    longitude: {{ .GatewayLongitude }}
    altitude: {{ .GatewayAltitude }}
{{- end }}
{{- if .HasNCells }}
  ncells:
{{- range .NCells }}
    - phys_cell_id: {{ .PhysicalCellID }}
{{- if .Frequency }}
      frequency: {{ .Frequency }}
{{- end }}
{{- end }}
{{- end }}
{{- if .HasReferenceLocation }}
  reference_location:
    latitude: {{ .RefLatitude }}
    longitude: {{ .RefLongitude }}
{{- end }}
{{- if .HasDistanceThreshold }}
  distance_threshold: {{ .DistanceThreshold }}
{{- end }}
{{- if .HasTService }}
  t_service: {{ .TService }}
{{- end }}
{{- if .MovingRefLocation }}
  moving_ref_location:
    latitude: {{ .MovingRefLatitude }}
    longitude: {{ .MovingRefLongitude }}
{{- end }}
{{- if .SatSwitchWithResync }}
  sat_switch_with_resync:
    target_pci: {{ .SatSwitchTargetPCI }}
    t304: {{ .SatSwitchT304 }}
{{- end }}
{{- if .HasPolarization }}
  polarization:
{{- if .PolarizationDL }}
    dl: {{ .PolarizationDL }}
{{- end }}
{{- if .PolarizationUL }}
    ul: {{ .PolarizationUL }}
{{- end }}
{{- end }}
{{- if .TAReportSet }}
  ta_report: {{ .TAReport }}
{{- end }}
{{- if .UlSyncValidityDurSet }}
  ntn_ul_sync_validity_dur: {{ .UlSyncValidityDur }}
{{- end }}

cell_cfg:
  sib:
    si_window_length: {{ .SIWindowLength }}
    si_sched_info:
      - si_period: {{ .SIPeriod }}
        sib_mapping: 19
        si_window_position: {{ .SIWindowPosition }}
  pdsch:
    max_nof_harq_retxs: {{ .PdschMaxHarqRetxs }}
  prach:
    max_msg3_harq_retx: {{ .PrachMaxMsg3HarqRetx }}

cu_cp:
  rrc:
    rrc_procedure_guard_time_ms: {{ .RrcGuardTimeMs }}
`

var parsedTemplate = template.Must(template.New("ocudu-ntn").Parse(configTemplate))

// ntnNeighborCellData holds per-neighbor data for template rendering.
type ntnNeighborCellData struct {
	PhysicalCellID int
	Frequency      int
}

type configData struct {
	PayloadType               string
	Koffset                   int
	TACommon                  int
	TAInfoExtended            bool
	TACommonDrift             int
	TACommonDriftVariant      int
	TACommonOffset            int
	UseOrbital                bool
	EphPosX                   int
	EphPosY                   int
	EphPosZ                   int
	EphVelX                   int
	EphVelY                   int
	EphVelZ                   int
	OrbSemiMajorAxis          int
	OrbEccentricity           int
	OrbInclination            int
	OrbRightAscension         int
	OrbArgOfPeriapsis         int
	OrbMeanAnomaly            int
	EpochTime                 bool
	EpochSFN                  int
	EpochSubframeNumber       int
	FeederLink                bool
	FeederDopplerCompensation bool
	FeederDLFreq              int64
	FeederULFreq              int64
	GatewayLocation           bool
	GatewayLatitude           int
	GatewayLongitude          int
	GatewayAltitude           int
	HasNCells                 bool
	NCells                    []ntnNeighborCellData
	HasReferenceLocation      bool
	RefLatitude               int
	RefLongitude              int
	HasDistanceThreshold      bool
	DistanceThreshold         int
	HasTService               bool
	TService                  int
	MovingRefLocation         bool
	MovingRefLatitude         int
	MovingRefLongitude        int
	SatSwitchWithResync       bool
	SatSwitchTargetPCI        int
	SatSwitchT304             int
	HasPolarization           bool
	PolarizationDL            string
	PolarizationUL            string
	TAReportSet               bool
	TAReport                  bool
	UlSyncValidityDurSet      bool
	UlSyncValidityDur         int
	PdschMaxHarqRetxs         int
	PrachMaxMsg3HarqRetx      int
	RrcGuardTimeMs            int
	SIWindowLength            int
	SIPeriod                  int
	SIWindowPosition          int
}

// SI scheduling defaults mirror the live-gNB-verified geo_ntn.yml values.
const (
	defaultSIWindowLength   = 5
	defaultSIPeriod         = 16
	defaultSIWindowPosition = 1
)

// GenerateConfig produces OCUDU-compatible NTN configuration YAML
// from an NTNCellConfigSpec. The output matches the CLI11 config format
// accepted by OCUDU gNB (CLI11 config format).
func GenerateConfig(spec *ntnv1alpha1.NTNCellConfigSpec) ([]byte, error) {
	if spec == nil {
		return nil, fmt.Errorf("spec must not be nil")
	}

	payloadType := spec.NTN.PayloadType
	if payloadType == "" {
		payloadType = "transparent"
	}

	data := configData{
		PayloadType:          payloadType,
		Koffset:              spec.NTN.CellSpecificKoffset,
		TACommon:             spec.NTN.TACommon,
		PdschMaxHarqRetxs:    0,
		PrachMaxMsg3HarqRetx: 0,
		RrcGuardTimeMs:       12800,
		SIWindowLength:       defaultSIWindowLength,
		SIPeriod:             defaultSIPeriod,
		SIWindowPosition:     defaultSIWindowPosition,
	}

	// Populate extended TA info fields.
	if spec.NTN.TAInfo != nil {
		data.TACommon = spec.NTN.TAInfo.TACommon
		// Emit drift/offset sub-fields only when at least one is non-zero.
		ta := spec.NTN.TAInfo
		if ta.TACommonDrift != 0 || ta.TACommonDriftVariant != 0 || ta.TACommonOffset != 0 {
			data.TAInfoExtended = true
			data.TACommonDrift = spec.NTN.TAInfo.TACommonDrift
			data.TACommonDriftVariant = spec.NTN.TAInfo.TACommonDriftVariant
			data.TACommonOffset = spec.NTN.TAInfo.TACommonOffset
		}
	}

	// Populate optional NTN fields (Rel-17 + Rel-18).
	if spec.NTN.EpochTime != nil {
		data.EpochTime = true
		data.EpochSFN = spec.NTN.EpochTime.SFN
		data.EpochSubframeNumber = spec.NTN.EpochTime.SubframeNumber
	}
	if spec.NTN.FeederLinkInfo != nil {
		data.FeederLink = true
		data.FeederDopplerCompensation = spec.NTN.FeederLinkInfo.EnableDopplerCompensation
		data.FeederDLFreq = spec.NTN.FeederLinkInfo.DLFreqHz
		data.FeederULFreq = spec.NTN.FeederLinkInfo.ULFreqHz
	}
	if spec.NTN.NTNGatewayLocation != nil {
		data.GatewayLocation = true
		data.GatewayLatitude = spec.NTN.NTNGatewayLocation.Latitude
		data.GatewayLongitude = spec.NTN.NTNGatewayLocation.Longitude
		data.GatewayAltitude = spec.NTN.NTNGatewayLocation.Altitude
	}
	if spec.NTN.MovingRefLocation != nil {
		data.MovingRefLocation = true
		data.MovingRefLatitude = spec.NTN.MovingRefLocation.Latitude
		data.MovingRefLongitude = spec.NTN.MovingRefLocation.Longitude
	}
	if spec.NTN.SatSwitchWithResync != nil {
		data.SatSwitchWithResync = true
		data.SatSwitchTargetPCI = spec.NTN.SatSwitchWithResync.TargetPCI
		data.SatSwitchT304 = spec.NTN.SatSwitchWithResync.T304
	}
	if spec.NTN.Polarization != nil {
		pol := spec.NTN.Polarization
		if pol.DL != "" || pol.UL != "" {
			data.HasPolarization = true
			data.PolarizationDL = pol.DL
			data.PolarizationUL = pol.UL
		}
	}
	if spec.NTN.TAReport != nil {
		data.TAReportSet = true
		data.TAReport = *spec.NTN.TAReport
	}
	if spec.NTN.NTNUlSyncValidityDur != nil {
		data.UlSyncValidityDurSet = true
		data.UlSyncValidityDur = *spec.NTN.NTNUlSyncValidityDur
	}

	if spec.NTN.EphemerisECEF != nil && spec.NTN.EphemerisOrbital != nil {
		return nil, fmt.Errorf("ephemerisECEF and ephemerisOrbital are mutually exclusive")
	}

	switch {
	case spec.NTN.EphemerisOrbital != nil:
		data.UseOrbital = true
		data.OrbSemiMajorAxis = spec.NTN.EphemerisOrbital.SemiMajorAxis
		data.OrbEccentricity = spec.NTN.EphemerisOrbital.Eccentricity
		data.OrbInclination = spec.NTN.EphemerisOrbital.Inclination
		data.OrbRightAscension = spec.NTN.EphemerisOrbital.RightAscension
		data.OrbArgOfPeriapsis = spec.NTN.EphemerisOrbital.ArgOfPeriapsis
		data.OrbMeanAnomaly = spec.NTN.EphemerisOrbital.MeanAnomaly
	case spec.NTN.EphemerisECEF != nil:
		data.EphPosX = spec.NTN.EphemerisECEF.PosX
		data.EphPosY = spec.NTN.EphemerisECEF.PosY
		data.EphPosZ = spec.NTN.EphemerisECEF.PosZ
		data.EphVelX = spec.NTN.EphemerisECEF.VelX
		data.EphVelY = spec.NTN.EphemerisECEF.VelY
		data.EphVelZ = spec.NTN.EphemerisECEF.VelZ
	default:
		return nil, fmt.Errorf("either ephemerisECEF or ephemerisOrbital must be set")
	}

	// Map Stage 3 multi-cell NTN fields.
	if len(spec.NTN.NeighborCells) > 0 {
		data.HasNCells = true
		for _, nc := range spec.NTN.NeighborCells {
			data.NCells = append(data.NCells, ntnNeighborCellData{
				PhysicalCellID: nc.PhysicalCellID,
				Frequency:      nc.Frequency,
			})
		}
	}
	if spec.NTN.ReferenceLocation != nil {
		data.HasReferenceLocation = true
		data.RefLatitude = spec.NTN.ReferenceLocation.Latitude
		data.RefLongitude = spec.NTN.ReferenceLocation.Longitude
	}
	if spec.NTN.DistanceThreshold != nil {
		data.HasDistanceThreshold = true
		data.DistanceThreshold = *spec.NTN.DistanceThreshold
	}
	if spec.NTN.TService != nil {
		data.HasTService = true
		data.TService = *spec.NTN.TService
	}

	// Apply custom overrides if provided.
	if spec.CellOverrides != nil {
		if spec.CellOverrides.PdschMaxHarqRetxs > 0 {
			data.PdschMaxHarqRetxs = spec.CellOverrides.PdschMaxHarqRetxs
		}
		if spec.CellOverrides.PrachMaxMsg3HarqRetx > 0 {
			data.PrachMaxMsg3HarqRetx = spec.CellOverrides.PrachMaxMsg3HarqRetx
		}
		if spec.CellOverrides.RrcGuardTimeMs > 0 {
			data.RrcGuardTimeMs = spec.CellOverrides.RrcGuardTimeMs
		}
		if sched := spec.CellOverrides.SIBSchedule; sched != nil {
			if sched.SIWindowLength > 0 {
				data.SIWindowLength = sched.SIWindowLength
			}
			if sched.SIPeriod > 0 {
				data.SIPeriod = sched.SIPeriod
			}
			if sched.SIWindowPosition != nil {
				data.SIWindowPosition = *sched.SIWindowPosition
			}
		}
	}

	var buf bytes.Buffer
	if err := parsedTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("executing config template: %w", err)
	}

	return buf.Bytes(), nil
}
